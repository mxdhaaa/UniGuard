"""
UniGuard Local Training Pipeline

Trains the RandomForest classifier and IsolationForest anomaly detector
on synthetic data generated by DemoService. All computation is local;
no external APIs, network calls, or model downloads.

Pipeline:
  DemoService.generate_batch()
    -> DirectionalFlowRecord (per-profile)
    -> FeatureEngine.extract_features()
    -> FeaturePreprocessor.preprocess()
    -> X (16 numeric features), y (profile label)

Train/Validation split strategy:
  - Training data: seed=42  (or user-supplied seed)
  - Validation data: seed=train_seed + 9999  (independent batch, different PRNG state)
  - This avoids contextual leakage from a naive random split of a correlated batch.

DISCLAIMER:
  These metrics are computed on synthetic data with distinct per-class behavioral
  distributions designed to be separable. High accuracy on synthetic data does NOT
  demonstrate equivalent real-world threat detection performance.
"""

from __future__ import annotations

import datetime
from collections import Counter
from typing import Dict, List, Tuple

from backend.app.services.demo_service import DemoService
from backend.app.core.preprocessing import FeaturePreprocessor, FEATURE_NAMES
from backend.app.ml.classifier import ThreatClassifier
from backend.app.ml.anomaly_detector import AnomalyDetector
from backend.app.ml.model_manager import (
    save_classifier,
    save_anomaly_detector,
    save_metadata,
)
from backend.app.schemas.ml import ModelMetadata, EvaluationMetrics, ModelReadinessState


# Canonical class list — must match ThreatClassifier.classes order
TARGET_CLASSES: List[str] = [
    "NORMAL",
    "SCANNING_LIKE",
    "DOS_LIKE",
    "BOTNET_LIKE",
    "EXFILTRATION_LIKE",
    "OTHER_SUSPICIOUS",
]


def _generate_dataset(
    seed: int, samples_per_class: int
) -> Tuple[List[List[float]], List[str]]:
    """
    Generate a balanced dataset for all six classes using DemoService.

    Each class is generated independently with a pure 100% profile mix.
    This ensures balanced class counts without re-sampling.

    Feature matrix X contains ONLY the 16 numeric features from FeaturePreprocessor.
    Labels y are the simulated_profile strings.

    Source IP, destination IP, flow_id, timestamps, and simulated_profile are
    NEVER included in X.

    Parameters
    ----------
    seed : int
        PRNG seed for DemoService — determines synthetic flow characteristics.
    samples_per_class : int
        Number of samples to generate per class.

    Returns
    -------
    Tuple[List[List[float]], List[str]]
        (X, y) — feature matrix and label list.
    """
    X: List[List[float]] = []
    y: List[str] = []

    for cls in TARGET_CLASSES:
        service = DemoService(default_seed=seed)
        # Generate only this class by using a pure 100% profile mix
        batch = service.generate_batch(count=samples_per_class, profile_mix={cls: 1.0})
        for item in batch:
            # item.preprocessed already contains the canonical 16 features
            X.append(item.preprocessed.values)
            # Label is the simulated_profile (not included in X)
            y.append(item.simulated_profile)

    return X, y


def train_models(seed: int = 42, samples_per_class: int = 200) -> ModelMetadata:
    """
    Full local training pipeline. Trains both models and persists artifacts.

    Steps:
    1. Generate balanced training data (seed=seed).
    2. Generate independent validation data (seed=seed+9999).
    3. Fit ThreatClassifier on all six classes.
    4. Fit AnomalyDetector ONLY on NORMAL training vectors.
    5. Evaluate classifier on validation set.
    6. Persist models and metadata.

    Parameters
    ----------
    seed : int
        Random seed for training data (default=42). Validation uses seed+9999.
    samples_per_class : int
        Samples per class (default=200 -> 1200 training total, 1200 validation total).

    Returns
    -------
    ModelMetadata
        Populated metadata object including evaluation metrics.
    """
    print(f"[Training] Generating training data (seed={seed}, {samples_per_class} per class)...")
    X_train, y_train = _generate_dataset(seed=seed, samples_per_class=samples_per_class)

    val_seed = seed + 9999
    print(f"[Training] Generating validation data (seed={val_seed}, {samples_per_class} per class)...")
    X_val, y_val = _generate_dataset(seed=val_seed, samples_per_class=samples_per_class)

    # -----------------------------------------------------------------------
    # Train classifier (all six classes)
    # -----------------------------------------------------------------------
    print("[Training] Fitting RandomForest classifier...")
    classifier = ThreatClassifier(n_estimators=200, random_state=seed)
    classifier.fit(X_train, y_train)

    # -----------------------------------------------------------------------
    # Train anomaly detector (NORMAL class only)
    # -----------------------------------------------------------------------
    normal_vectors = [
        vec for vec, label in zip(X_train, y_train) if label == "NORMAL"
    ]
    print(f"[Training] Fitting IsolationForest on {len(normal_vectors)} NORMAL vectors...")
    anomaly_detector = AnomalyDetector(random_state=seed, contamination=0.1)
    anomaly_detector.fit(normal_vectors)

    # -----------------------------------------------------------------------
    # Evaluate classifier on independent validation set
    # -----------------------------------------------------------------------
    class_counts: Dict[str, int] = dict(Counter(y_train))
    print("[Training] Evaluating classifier on validation set...")
    eval_metrics: EvaluationMetrics = classifier.evaluate(
        X_val,
        y_val,
        train_samples_count=len(y_train),
        samples_per_class=class_counts,
    )

    print(f"[Training] Accuracy: {eval_metrics.accuracy:.4f}")
    print(f"[Training] Macro F1: {eval_metrics.macro_f1:.4f}")

    # -----------------------------------------------------------------------
    # Build metadata
    # -----------------------------------------------------------------------
    metadata = ModelMetadata(
        model_name="UniGuardML",
        model_version="0.1.0",
        feature_schema_version="1.0",
        feature_names=list(FEATURE_NAMES),
        classes=list(classifier.classes),
        random_seed=seed,
        training_source="synthetic_demo_data_DemoService",
        training_sample_count=len(y_train),
        class_distribution=class_counts,
        validation_metrics=eval_metrics.model_dump(),
        isolation_forest_configuration={
            "n_estimators": 100,
            "contamination": anomaly_detector.contamination,
            "random_state": seed,
            "training_class": "NORMAL_only",
            "training_samples": len(normal_vectors),
        },
        created_at=(
            datetime.datetime.now(datetime.timezone.utc)
            .replace(microsecond=0)
            .isoformat()
        ),
        readiness_state=ModelReadinessState.READY,
    )

    # -----------------------------------------------------------------------
    # Persist
    # -----------------------------------------------------------------------
    print("[Training] Saving classifier...")
    save_classifier(classifier, metadata)
    print("[Training] Saving anomaly detector...")
    save_anomaly_detector(anomaly_detector, metadata)
    print("[Training] Saving metadata...")
    save_metadata(metadata)
    print("[Training] Complete. Models saved to backend/app/ml/models/")

    return metadata
